import WebSocket from "ws";
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
const ws = new WebSocket("ws://127.0.0.1:8099/ws");
await new Promise((res, rej) => { ws.once("open", res); ws.once("error", rej); });
const seen = [];
ws.on("message", (raw) => seen.push(JSON.parse(raw.toString())));
ws.send(JSON.stringify({ type: "hello" }));
await sleep(300);
const leaseEpoch = seen.at(-1).leaseEpoch;
ws.send(JSON.stringify({ type: "game_start", requestId: "smoke-1", leaseEpoch }));
await sleep(400);
const state = seen.filter(m => m.type === "game_state").at(-1);
const board = state?.board;
const out = { board: board && { cells: board.cells.length, hidden: board.cells.filter(c => c.state === "hidden").length, revision: board.revision, mines: board.mineCount } };
ws.send(JSON.stringify({ type: "dig_commit", gameId: board.gameId, x: -3.6, z: -3.6, expectedRevision: board.revision, leaseEpoch }));
await sleep(400);
const dig1 = seen.filter(m => m.type === "dig_result").at(-1);
out.dig1 = { ok: dig1.ok, reason: dig1.reason, changed: dig1.changedCells?.length, status: dig1.status, revision: dig1.revision };
ws.send(JSON.stringify({ type: "dig_commit", gameId: board.gameId, x: -3.6, z: -3.6, expectedRevision: dig1.revision, leaseEpoch }));
await sleep(400);
const dig2 = seen.filter(m => m.type === "dig_result").at(-1);
out.dig2 = { ok: dig2.ok, reason: dig2.reason };
ws.send(JSON.stringify({ type: "dig_commit", gameId: "bogus", x: -3.6, z: -3.6, leaseEpoch }));
await sleep(400);
const dig3 = seen.filter(m => m.type === "dig_result").at(-1);
out.dig3 = { ok: dig3.ok, reason: dig3.reason };
console.log(JSON.stringify(out, null, 1));
ws.close();
